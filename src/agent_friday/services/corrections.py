"""Owner corrections as first-class events (north star §29.9-1, §15.6-1, §36.2-8).

When the owner corrects something Friday holds (a memory-card line, a wiki
claim, later a fact or a graph entity) the correction is recorded here as one
event, not only applied as a text replace:

  id               ``corr-`` + 12 hex
  at               epoch seconds
  by               always ``"owner"``: Friday's own changes are never recorded here
  store            ``card`` | ``conversation`` | ``wiki`` | ``fact`` | ``kg``
  action           ``corrected`` | ``marked_wrong`` | ``restored``
  claim            the old text (the owner's own data, SEALED)
  correction       the new text, or ``"removed"`` (SEALED)
  reason           the owner's reason, or the standard one for the path
  sources          ids of the prior items: ``card:user#3``, ``wiki:notes/a.md#Section``,
                   ``msg:<id>``, ``fact:<id>``, ``kg:<entity>``
  affected         ids of the items superseded or updated (and derived items re-queued)
  repair           what was done, as counts (``superseded_turns``, ``pages_changed``,
                   ``graph_reindex_queued`` ...)
  restores         for ``restored``: the ids of the events it undoes
  history          SEALED list of the prior text each changed item held, so a
                   correction of a store with no history of its own (the wiki)
                   keeps the original in history
  regression_test  False at first; the owner can tick "keep this as a test"
                   (``set_test``): their own {question, expected} is kept,
                   sealed, for a future eval. Never generated by Friday.

Storage: ``<Friday home>/corrections/corrections.jsonl``. Append only: a
restore is a new ``restored`` event that names the one it undoes, and a test
flag is a ``test_flag`` row; ``events()`` folds them. The only rewrite is a
forget (``people_purge``): forgetting a person removes the rows that name them.

Sealing: the text fields go through ``credential_store.protect`` (the same
``enc:`` envelope memory_proposals uses), so the old claim never sits in a
plain file beside the store it was corrected out of. A row whose text cannot
be opened (the keystore is unavailable) reads as empty, never as plain text.

Leaf module: no Flask; ``record`` never raises to a caller.
"""
from __future__ import annotations

import base64
import json
import os
import re
import threading
import time
import uuid
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional

from agent_friday.paths import friday_home

STORES = ("card", "conversation", "wiki", "fact", "kg")
ACTIONS = ("corrected", "marked_wrong", "restored")

#: The list the owner sees is bounded.
LIST_MAX = 100
#: Text kept per field (characters, before sealing).
TEXT_MAX = 2000
#: An owner's golden for a regression test.
QUESTION_MAX = 300
EXPECTED_MAX = 400
#: Ids kept per event.
IDS_MAX = 200

#: A correction this recent is cited in the prompt as ``[correction:<date>]``.
CITE_DAYS = 30

REMOVED = "removed"

_SEALED = "enc:"
_LOCK = threading.RLock()


def _dir() -> Path:
    return friday_home() / "corrections"


def _path() -> Path:
    return _dir() / "corrections.jsonl"


def new_id() -> str:
    return "corr-" + uuid.uuid4().hex[:12]


# ── sealing ───────────────────────────────────────────────────────────────────
def _seal(text: Any) -> str:
    s = str(text or "")
    if not s:
        return ""
    from agent_friday.services import credential_store as cs
    blob, _method = cs.protect(s.encode("utf-8"))
    return _SEALED + base64.b64encode(blob).decode("ascii")


def _open(text: Any) -> str:
    if not isinstance(text, str) or not text.startswith(_SEALED):
        return ""                      # nothing here is ever plain text
    try:
        from agent_friday.services import credential_store as cs
        return cs.unprotect(base64.b64decode(text[len(_SEALED):])).decode("utf-8")
    except Exception:  # noqa: BLE001 - what cannot be opened is shown as nothing
        return ""


# ── the file ──────────────────────────────────────────────────────────────────
def _rows() -> List[Dict[str, Any]]:
    try:
        lines = _path().read_text(encoding="utf-8").splitlines()
    except (FileNotFoundError, OSError):
        return []
    out = []
    for ln in lines:
        try:
            r = json.loads(ln)
        except Exception:
            continue
        if isinstance(r, dict):
            out.append(r)
    return out


def _append(row: Dict[str, Any]) -> None:
    p = _path()
    p.parent.mkdir(parents=True, exist_ok=True)
    with _LOCK:
        with open(p, "a", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            f.flush()
            os.fsync(f.fileno())


def _rewrite(rows: List[Dict[str, Any]]) -> None:
    p = _path()
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(p.name + f".{uuid.uuid4().hex[:8]}.tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, p)


def _ids(values: Optional[Iterable[Any]]) -> List[str]:
    out: List[str] = []
    for v in values or []:
        s = str(v or "").strip()[:200]
        if s and s not in out:
            out.append(s)
        if len(out) >= IDS_MAX:
            break
    return out


# ── recording ─────────────────────────────────────────────────────────────────
def record(store: str, action: str, *, claim: str = "", correction: str = "", reason: str = "",
           sources: Optional[Iterable[Any]] = None, affected: Optional[Iterable[Any]] = None,
           repair: Optional[Dict[str, Any]] = None, restores: Optional[Iterable[Any]] = None,
           history: Optional[List[Dict[str, Any]]] = None, event_id: str = "",
           by: str = "owner") -> str:
    """Record one owner correction; returns its id ("" when nothing was
    recorded). Only the owner's corrections are events: any other `by` is
    refused. Never raises."""
    if by != "owner" or store not in STORES or action not in ACTIONS:
        return ""
    eid = event_id or new_id()
    try:
        rep = {}
        for k, v in (repair or {}).items():
            if isinstance(v, bool) or isinstance(v, int):
                rep[str(k)[:60]] = v
        row = {
            "kind": "event", "id": eid, "at": time.time(), "by": "owner",
            "store": store, "action": action,
            "claim": _seal(str(claim or "")[:TEXT_MAX]),
            "correction": _seal(str(correction or "")[:TEXT_MAX]),
            "reason": str(reason or "")[:300],
            "sources": _ids(sources), "affected": _ids(affected),
            "repair": rep, "restores": _ids(restores),
            "history": _seal(json.dumps(history or [], ensure_ascii=False)[:20000]) if history else "",
            "regression_test": False,
        }
        _append(row)
        return eid
    except Exception as e:  # noqa: BLE001 - a correction is applied even when its record fails
        print(f"  [CORRECTIONS] not recorded (non-fatal): {e}")
        return ""


def set_test(event_id: str, on: bool, question: str = "", expected: str = "") -> Dict[str, Any]:
    """The owner ticks or unticks "keep this as a test" on one event. The
    golden is the owner's own question and expected answer; nothing is
    generated. Appends a flag row; the event itself is not rewritten."""
    eid = str(event_id or "")
    ev = next((r for r in _rows() if r.get("kind") == "event" and r.get("id") == eid), None)
    if not ev:
        return {"ok": False, "error": "that correction is not there"}
    q = " ".join(str(question or "").split())[:QUESTION_MAX]
    x = " ".join(str(expected or "").split())[:EXPECTED_MAX]
    row = {"kind": "test_flag", "event_id": eid, "at": time.time(), "on": bool(on),
           "golden": _seal(json.dumps({"question": q, "expected": x}, ensure_ascii=False))
           if (on and (q or x)) else ""}
    try:
        _append(row)
    except Exception as e:  # noqa: BLE001
        return {"ok": False, "error": str(e)[:120]}
    return {"ok": True, "id": eid, "regression_test": bool(on),
            "golden": {"question": q, "expected": x} if (on and (q or x)) else None}


# ── reading ───────────────────────────────────────────────────────────────────
def _fold(rows: List[Dict[str, Any]], open_text: bool) -> List[Dict[str, Any]]:
    events: Dict[str, Dict[str, Any]] = {}
    order: List[str] = []
    for r in rows:
        if r.get("kind") == "event" and r.get("id"):
            ev = dict(r)
            if open_text:
                ev["claim"] = _open(r.get("claim"))
                ev["correction"] = _open(r.get("correction"))
                try:
                    ev["history"] = json.loads(_open(r.get("history")) or "[]")
                except Exception:
                    ev["history"] = []
            else:
                ev.pop("claim", None)
                ev.pop("correction", None)
                ev.pop("history", None)
            ev["golden"] = None
            ev["restored_by"] = []
            events[ev["id"]] = ev
            order.append(ev["id"])
    for r in rows:
        if r.get("kind") == "test_flag" and r.get("event_id") in events:
            ev = events[r["event_id"]]
            ev["regression_test"] = bool(r.get("on"))
            g = None
            if r.get("on") and r.get("golden") and open_text:
                try:
                    g = json.loads(_open(r.get("golden")) or "null")
                except Exception:
                    g = None
            ev["golden"] = g
    for eid in order:
        for orig in events[eid].get("restores") or []:
            if orig in events:
                events[orig]["restored_by"].append(eid)
    return [events[i] for i in order]


def events(n: int = 50, open_text: bool = True) -> List[Dict[str, Any]]:
    """The owner's corrections, newest first, at most LIST_MAX."""
    try:
        n = max(1, min(int(n), LIST_MAX))
    except (TypeError, ValueError):
        n = 50
    return list(reversed(_fold(_rows(), open_text)))[:n]


def get(event_id: str) -> Optional[Dict[str, Any]]:
    return next((e for e in _fold(_rows(), True) if e.get("id") == str(event_id or "")), None)


def for_item(item_id: str) -> List[Dict[str, Any]]:
    """The why path: every correction that names `item_id` as a source or as
    something it affected (a message id, ``card:user#2``, a wiki page)."""
    want = str(item_id or "")
    if not want:
        return []
    return [e for e in _fold(_rows(), True)
            if want in (e.get("sources") or []) or want in (e.get("affected") or [])]


def cite(at: float) -> str:
    """``[correction:YYYY-MM-DD]`` for an event time."""
    try:
        return "[correction:" + time.strftime("%Y-%m-%d", time.localtime(float(at))) + "]"
    except Exception:
        return "[correction]"


# ── forget-person ─────────────────────────────────────────────────────────────
def _name_patterns(names) -> list:
    wanted = [n for n in {" ".join(str(x or "").split()).lower() for x in (names or [])} if len(n) >= 3]
    return [re.compile(r"\b" + r"\s+".join(re.escape(w) for w in n.split(" ")) + r"\b", re.IGNORECASE)
            for n in wanted]


def _names_row(r: Dict[str, Any], pats) -> bool:
    hay = " ".join([_open(r.get("claim")), _open(r.get("correction")), _open(r.get("history")),
                    _open(r.get("golden"))])
    return any(p.search(hay) for p in pats)


def people_find(names, emails) -> int:
    pats = _name_patterns(set(names or ()) | set(emails or ()))
    if not pats:
        return 0
    return sum(1 for r in _rows() if _names_row(r, pats))


def people_purge(names, emails) -> int:
    """Forgetting a person removes every correction row that names them (and
    the flag rows of those events)."""
    pats = _name_patterns(set(names or ()) | set(emails or ()))
    if not pats:
        return 0
    with _LOCK:
        rows = _rows()
        gone = {r.get("id") for r in rows if r.get("kind") == "event" and _names_row(r, pats)}
        keep = [r for r in rows
                if not (r.get("kind") == "event" and r.get("id") in gone)
                and not (r.get("kind") == "test_flag" and (r.get("event_id") in gone or _names_row(r, pats)))]
        if len(keep) != len(rows):
            _rewrite(keep)
        return len(rows) - len(keep)
